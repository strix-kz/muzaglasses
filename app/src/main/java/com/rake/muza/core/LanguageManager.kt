object LanguageManager {
    private const val PREFS_NAME = "muza_language_prefs"
    private const val KEY_LANG = "selected_language"
    private var prefs: SharedPreferences? = null

    private val _language = MutableStateFlow(AppLanguage.KK)
    val language: StateFlow<AppLanguage> = _language.asStateFlow()

    private val _strings = MutableStateFlow(stringsFor(AppLanguage.KK))
    val strings: StateFlow<MuzaStrings> = _strings.asStateFlow()

    val currentLanguage: AppLanguage get() = _language.value
    val currentStrings: MuzaStrings get() = _strings.value

    fun init(context: Context) {
        val sp = context.applicationContext.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        prefs = sp
        val saved = AppLanguage.fromCode(sp.getString(KEY_LANG, AppLanguage.KK.code))
        _language.value = saved
        _strings.value = stringsFor(saved)
    }

    fun setLanguage(lang: AppLanguage) {
        _language.value = lang
        _strings.value = stringsFor(lang)
        prefs?.edit()?.putString(KEY_LANG, lang.code)?.apply()
    }

